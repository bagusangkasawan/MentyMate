async function ensureSupportServicesSeeded() {
  try {
    for (const svc of SEED_SERVICES) {
      const { eligibilityEn, eligibilityId, ...insertData } = svc;

      await SupportService.updateOne(
        { name: svc.name, country: svc.country },
        {
          $setOnInsert: insertData,
          $set: {
            eligibilityEn,
            eligibilityId,
          },
        },
        { upsert: true }
      );
    }
  } catch (err) {
    console.error('Failed to seed support services:', err.message);
  }
}

